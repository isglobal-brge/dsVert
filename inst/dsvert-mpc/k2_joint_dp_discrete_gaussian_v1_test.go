func TestJointDPGaussianSymmetricProjectionDoesNotIncreaseTwoDrawMagnitude(t *testing.T) {
	for maximum := int64(0); maximum <= 16; maximum++ {
		bound := big.NewInt(maximum)
		for left := int64(-64); left <= 64; left++ {
			for right := int64(-64); right <= 64; right++ {
				projectedLeft := jointDPGaussianProject(big.NewInt(left), bound)
				projectedRight := jointDPGaussianProject(big.NewInt(right), bound)
				projectedMagnitude := new(big.Int).Abs(new(big.Int).Add(
					projectedLeft, projectedRight))
				originalMagnitude := new(big.Int).Abs(new(big.Int).Add(
					big.NewInt(left), big.NewInt(right)))
				if projectedMagnitude.Cmp(originalMagnitude) > 0 {
					t.Fatalf("M=%d x=%d y=%d: projected magnitude %s > %s",
						maximum, left, right, projectedMagnitude, originalMagnitude)
				}
			}
		}
	}
}

