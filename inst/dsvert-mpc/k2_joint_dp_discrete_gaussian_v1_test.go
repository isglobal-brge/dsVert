func jointDPGaussianTestGenericHockeyStick(
	left, right map[int]*big.Rat, expEpsilon *big.Rat,
) *big.Rat {
	keys := make(map[int]struct{}, len(left)+len(right))
	for value := range left {
		keys[value] = struct{}{}
	}
	for value := range right {
		keys[value] = struct{}{}
	}
	result := new(big.Rat)
	for value := range keys {
		leftMass := left[value]
		if leftMass == nil {
			leftMass = new(big.Rat)
		}
		rightMass := right[value]
		if rightMass == nil {
			rightMass = new(big.Rat)
		}
		difference := new(big.Rat).Sub(leftMass,
			new(big.Rat).Mul(expEpsilon, rightMass))
		if difference.Sign() > 0 {
			result.Add(result, difference)
		}
	}
	return result
}

func jointDPGaussianTestTranslatePMF(
	pmf map[int]*big.Rat, offset int,
) map[int]*big.Rat {
	result := make(map[int]*big.Rat, len(pmf))
	for value, mass := range pmf {
		result[value+offset] = new(big.Rat).Set(mass)
	}
	return result
}

func TestJointDPGaussianKnownPeerViewIsOnlyFixedPostProcessing(t *testing.T) {
	// This distribution-independent oracle locks the key conditional-view
	// step: after fixing the corrupt peer's share, seed and complete draw, its
	// contribution is a translation. Translation preserves both directed
	// hockey-stick divergences of the remaining honest full mechanism.
	honestLeft := map[int]*big.Rat{
		-1: big.NewRat(1, 4), 0: big.NewRat(1, 2), 1: big.NewRat(1, 4),
	}
	honestRight := map[int]*big.Rat{
		0: big.NewRat(1, 4), 1: big.NewRat(1, 2), 2: big.NewRat(1, 4),
	}
	expEpsilon := big.NewRat(3, 2)
	forward := jointDPGaussianTestGenericHockeyStick(
		honestLeft, honestRight, expEpsilon)
	reverse := jointDPGaussianTestGenericHockeyStick(
		honestRight, honestLeft, expEpsilon)
	for corruptKnownContribution := -16; corruptKnownContribution <= 16; corruptKnownContribution++ {
		translatedLeft := jointDPGaussianTestTranslatePMF(
			honestLeft, corruptKnownContribution)
		translatedRight := jointDPGaussianTestTranslatePMF(
			honestRight, corruptKnownContribution)
		if jointDPGaussianTestGenericHockeyStick(
			translatedLeft, translatedRight, expEpsilon).Cmp(forward) != 0 ||
			jointDPGaussianTestGenericHockeyStick(
				translatedRight, translatedLeft, expEpsilon).Cmp(reverse) != 0 {
			t.Fatal("conditioning on one peer's known draw changed privacy divergence")
		}
	}
	plan, err := jointDPPlanVectorGaussian(jointDPGaussianPlanInput{
		Epsilon: "1", Delta: "0.000001", L2SensitivitySteps: "1",
		TotalCoordinateCount: 8,
	})
	if err != nil || !plan.AtLeastOneHonestNoisePeer ||
		plan.MaximumColludingNoisePeers != 1 ||
		plan.ReleaseDeltaAggregation != "max_per_peer_not_sum" ||
		plan.SourceShareHidingPrecondition == "" {
		t.Fatalf("conditional adversary-view certificate missing: %#v %v", plan, err)
	}
}

func benchmarkJointDPGaussianFixedNoise(b *testing.B, coordinates int) {
	seed := sha256.Sum256([]byte("gaussian-scalable-fallback-benchmark"))
	source := make([]*big.Int, coordinates)
	upper := make([]int64, coordinates)
	shifts := make([]int, coordinates)
	for index := range source {
		source[index] = new(big.Int)
		upper[index] = 1_000_000
	}
	input := jointDPGaussianTestInput(
		b, "peer-a", seed, source, upper, shifts, 0, coordinates)
	spec, err := jointDPGaussianParseSpec(input)
	if err != nil {
		b.Fatal(err)
	}
	b.ResetTimer()
	for iteration := 0; iteration < b.N; iteration++ {
		noise, noiseErr := jointDPGaussianNoise(seed, spec)
		if noiseErr != nil {
			b.Fatal(noiseErr)
		}
		exactGCZeroBigInts(noise)
	}
	b.StopTimer()
	b.ReportMetric(0, "secure-cdf-gates")
	b.ReportMetric(float64(coordinates), "coordinates")
}

func BenchmarkJointDPGaussianScalableFallbackP1(b *testing.B) {
	benchmarkJointDPGaussianFixedNoise(b, 1)
}

