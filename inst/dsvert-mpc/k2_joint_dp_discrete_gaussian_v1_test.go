	t.Helper()
	transcript := sha256.Sum256([]byte("gaussian/transcript/" + t.Name()))
	context := jointDPCommitmentContext(
		transcript, jointDPGaussianCommitmentPurpose, peer)
	commitment := jointDPSeedCommitment(context, seed)
	release := sha256.Sum256([]byte("gaussian/release/" + t.Name()))
	encoded, err := exactGCEncodeWorkerCanonicalShares(source,
		exactGCCircuitSpec{Operation: jointDPVectorOperation,
			RingBits: 128, FracBits: 0, VectorLen: len(source)})
